def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--names", default="", help="逗号分隔的三位成员姓名，按 统筹,开发,运营 顺序")
    args = parser.parse_args()
    names = [n.strip() for n in args.names.split(",") if n.strip()] if args.names else []

    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for idx, r in enumerate(ROLES):
        name = names[idx] if idx < len(names) else "{姓名}"
        body = (
            HEADER.format(name=name, role=r["role"])
            + "\n## 一、我承担的工作\n\n" + r["duty"]
            + "\n\n## 二、我在这次课程里最重要的收获\n\n" + r["learn"]
            + "\n\n## 三、我遇到的最大困难与解决过程\n\n" + r["difficulty"]
            + "\n\n## 四、我如何使用 Agent，以及人工介入的地方\n\n" + r["agent"]
            + FOOTER.format(next_step=r["next_step"])
        )
        fname = f"{name}_个人总结.md" if name != "{姓名}" else f"{{姓名}}_{r['key']}_个人总结.md"
        path = os.path.join(OUT_DIR, fname)
        with open(path, "w", encoding="utf-8") as f:
            f.write(body)
        written.append(path)
        print(f"已生成：{fname}")

    print(f"\n共 {len(written)} 份。姓名占位符需由成员自行填写——姓名属个人信息，不由工具代填。")
    if not names:
        print("如需直接生成带姓名的文件：python deliverables/build/generate_personal.py --names \"张三,李四,王五\"")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
